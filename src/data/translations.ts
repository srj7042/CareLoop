export const t = (arg1: string, arg2?: string): string => {
  const isArg1Lang = ["en", "ta", "te", "hi", "mr"].includes(arg1);
  const lang = (isArg1Lang ? arg1 : arg2 || "en") as Lang;
  const key = isArg1Lang ? arg2 || "" : arg1;
  const dict = translations[lang] || translations.en;
  return dict[key] || translations.en[key] || key;
};

